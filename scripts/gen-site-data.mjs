#!/usr/bin/env node
/**
 * Generates the project-site object matrix from the supported-types reference.
 *
 * Source of truth: `docs/supported.md` (the Type × command matrix).
 * Output: `site/assets/objects.js` — a plain script so the static page also
 * works when opened without a server.
 *
 * The generator normalizes the matrix cells into a small rendering contract
 * (`direct` / `file` / `rf` / `tmp` / `none`) and validates the published
 * counts before writing. `--check` is wired into `npm run verify` so the
 * site cannot drift from the docs.
 *
 * Usage:
 *   node scripts/gen-site-data.mjs
 *   node scripts/gen-site-data.mjs --check
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const docPath = path.join(repoRoot, 'docs', 'supported.md');
const outPath = path.join(repoRoot, 'site', 'assets', 'objects.js');
const checkOnly = process.argv.includes('--check');

const categories = [
  { id: 'source', label: 'Source code', hint: 'Classes, interfaces, programs, function groups, type pools, packages' },
  { id: 'cds', label: 'CDS & RAP', hint: 'CDS views, metadata, access control, RAP behavior and services' },
  { id: 'ddic', label: 'DDIC', hint: 'Tables, structures, domains, data elements, views, search helps' },
  { id: 'services', label: 'Services & UI', hint: 'SICF nodes, transactions, XSLT, destinations, UCON, OAuth' },
  { id: 'jobs', label: 'ATC & jobs', hint: 'ATC configuration, application jobs, job definitions' },
  { id: 'security', label: 'Security', hint: 'Authorization fields, objects, classes, groups and defaults' },
  { id: 'aff', label: 'AFF basis', hint: 'Application logs, change documents, event bindings, enhancements' },
];

const categoryByType = new Map();
for (const [category, types] of Object.entries({
  source: ['CLAS', 'INTF', 'PROG', 'FUGR', 'TYPE', 'DEVC'],
  cds: ['DDLS', 'DDLA', 'DDLX', 'DCLS', 'SRVD', 'SRVB', 'BDEF', 'DTDC', 'DTEB', 'DSFD', 'DSFI', 'DRTY'],
  ddic: ['TABL', 'STRU', 'DOMA', 'DTEL', 'TTYP', 'VIEW', 'SHLP', 'ENQU', 'NROB', 'MSAG'],
  services: ['HTTP', 'TRAN', 'XSLT', 'SM59', 'SRFC', 'OA2P', 'UCON_HTTP'],
  jobs: ['CHKC', 'CHKO', 'CHKV', 'SAJC', 'SAJT', 'JOBD'],
  security: ['AUTH', 'SUSC', 'SUCU', 'SUSH', 'SUSO'],
  aff: ['APLO', 'CHDO', 'EVTB', 'SMBC', 'ENHO', 'ENHS'],
})) {
  for (const type of types) categoryByType.set(type, category);
}

const markdown = fs.readFileSync(docPath, 'utf8');
const rows = [];

for (const line of markdown.split('\n')) {
  if (!line.startsWith('| `')) continue;
  const cells = line.slice(1, -1).split('|').map((cell) => cell.trim());
  if (cells.length !== 8) continue;
  const code = cells[0].replaceAll('`', '');
  if (!/^[A-Z0-9_]+$/.test(code)) continue;
  const [, name, createCell, pullCell, pushCell, deleteCell, channelCell, artifacts] = cells;
  if (rows.some((row) => row.code === code)) continue;

  const create = createCell.includes('✅')
    ? createCell.includes('(RF only)') ? 'rf' : createCell.includes('`--file`') ? 'file' : 'direct'
    : 'none';
  const remove = deleteCell.includes('✅') ? (deleteCell.includes('`$TMP`') ? 'tmp' : 'direct') : 'none';
  const channel = channelCell.includes('auto') ? 'auto' : channelCell.includes('ICF') ? 'icf' : 'adt';
  const category = categoryByType.get(code);
  if (!category) throw new Error(`No site category mapped for object type ${code}`);

  rows.push({
    code,
    name,
    category,
    channel,
    create,
    pull: pullCell.includes('✅'),
    push: pushCell.includes('✅'),
    delete: remove,
    artifacts: artifacts.replaceAll('`', ''),
  });
}

if (rows.length === 0) throw new Error('No object rows parsed from docs/supported.md');

// Keep a stable presentation order: category order, then type code.
rows.sort((a, b) => {
  const categoryDelta = categories.findIndex((c) => c.id === a.category) - categories.findIndex((c) => c.id === b.category);
  return categoryDelta || a.code.localeCompare(b.code);
});

const stats = {
  total: rows.length,
  create: rows.filter((row) => row.create !== 'none').length,
  pull: rows.filter((row) => row.pull).length,
  push: rows.filter((row) => row.push).length,
  delete: rows.filter((row) => row.delete !== 'none').length,
  readOnly: rows.filter((row) => !row.push && row.create === 'none' && row.delete === 'none').length,
  categories: categories.length,
};

if (stats.total !== 52 || stats.create !== 50 || stats.pull !== 52 || stats.push !== 48 || stats.delete !== 50) {
  throw new Error(`Object matrix counts changed: ${JSON.stringify(stats)}. Update the site copy and this guard together.`);
}

const header = [
  '// Generated by scripts/gen-site-data.mjs from docs/supported.md.',
  '// Do not edit by hand. Run `npm run site:data` to regenerate.',
  '',
];
const body = [
  `window.ABAP_CATEGORIES = ${JSON.stringify(categories, null, 2)};`,
  '',
  `window.ABAP_OBJECTS = ${JSON.stringify(rows, null, 2)};`,
  '',
  `window.ABAP_STATS = ${JSON.stringify(stats, null, 2)};`,
  '',
].join('\n');
const output = header.join('\n') + body;

if (checkOnly) {
  if (!fs.existsSync(outPath)) {
    console.error('site data missing: run `npm run site:data`');
    process.exit(1);
  }
  if (fs.readFileSync(outPath, 'utf8') !== output) {
    console.error('site data is out of date: run `npm run site:data` and commit the result');
    process.exit(1);
  }
  console.log(`site data is up to date (${stats.total} object types)`);
} else {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, output);
  console.log(`wrote ${path.relative(repoRoot, outPath)} (${stats.total} object types)`);
}
